from mask import mask

CASES = [
    ("연락처 010-1234-5678로 주세요", "연락처 [전화]로 주세요"),
    ("01098765432 이 번호요", "[전화] 이 번호요"),
    ("사무실 02-123-4567", "사무실 [전화]"),
    ("+82 10-1234-5678", "[전화]"),
    ("메일은 kim.ceo@abc-corp.co.kr 입니다", "메일은 [메일] 입니다"),
    ("국민 123456-01-234567 로 입금", "국민 [번호] 로 입금"),
    ("카드 1234 5678 9012 3456", "카드 [번호]"),
    ("사업자번호 123-45-67890", "사업자번호 [번호]"),
    ("주민번호 900101-1234567", "주민번호 [주민번호]"),
    ("비밀번호: Abc!2345 입니다", "비밀번호: [가림] 입니다"),
    ("비번은 qwer1234", "비번은 [가림]"),
    ("PW=hello123", "PW=[가림]"),
    ("인증번호 482913", "인증번호 [가림]"),
    # 가리면 안 되는 것
    ("투자금 1,500,000,000원", "투자금 1,500,000,000원"),
    ("11월 4일 15시 미팅", "11월 4일 15시 미팅"),
    ("지분 12.5%", "지분 12.5%"),
]


WORK_CASES = [
    ("연락처 010-1234-5678, kim@abc.co.kr", "연락처 010-1234-5678, kim@abc.co.kr"),
    ("국민 123456-01-234567 로 입금", "국민 123456-01-234567 로 입금"),
    ("비번은 qwer1234", "비번은 [가림]"),
    ("인증번호 482913", "인증번호 [가림]"),
    ("주민번호 900101-1234567", "주민번호 [주민번호]"),
]


def test_strict():
    for src, want in CASES:
        assert mask(src, "strict") == want, (src, mask(src, "strict"), want)


def test_work():
    for src, want in WORK_CASES:
        assert mask(src, "work") == want, (src, mask(src, "work"), want)
